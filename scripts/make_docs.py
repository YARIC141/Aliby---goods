# ─── helpers ──────────────────────────────────────────────────────────────────

def new_doc():
    doc = Document()
    for s in doc.styles:
        if s.name == 'Normal':
            s.font.name = 'Times New Roman'
            s.font.size = Pt(12)
    # margins 2.5 cm
    for sec in doc.sections:
        sec.top_margin    = Cm(2.5)
        sec.bottom_margin = Cm(2.5)
        sec.left_margin   = Cm(3)
        sec.right_margin  = Cm(1.5)
    return doc

def h1(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text.upper())
    run.bold = True
    run.font.size = Pt(14)
    p.space_after = Pt(6)
    return p

def h2(doc, text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(12)
    p.space_before = Pt(10)
    p.space_after   = Pt(4)
    return p

def para(doc, text, indent=False, bold_prefix=None):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(1.25) if indent else None
    p.space_after = Pt(2)
    if bold_prefix:
        run = p.add_run(bold_prefix)
        run.bold = True
        p.add_run(text)
    else:
        p.add_run(text)
    return p

def bullet(doc, text, level=0):
    p = doc.add_paragraph(style='List Bullet')
    p.add_run(text)
    p.space_after = Pt(1)
    return p

def divider(doc):
    doc.add_paragraph()

